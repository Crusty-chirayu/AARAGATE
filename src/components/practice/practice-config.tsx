"use client";

import * as React from "react";
import { Sparkles } from "lucide-react";
import { Button } from "@/components/ui/button";
import { Card, CardBody, CardHeader } from "@/components/ui/card";
import { Field, Input } from "@/components/ui/input";
import { Alert } from "@/components/ui/alert";
import { DEMO_MODE } from "@/lib/env";
import {
  MAX_PRACTICE_QUESTIONS,
  PRACTICE_DIFFICULTIES,
  validatePracticeConfig,
  type PracticeConfig,
  type PracticeDifficulty,
} from "@/lib/practice";
import { sampleSubjects, sampleTopics } from "@/lib/sample-questions";
import type { QuestionKind } from "@/lib/quiz";

/**
 * Practice configuration.
 *
 * The request is validated with the same `validatePracticeConfig` the server
 * path uses, so a bad configuration is rejected here with a readable reason
 * instead of being sent and failing remotely. Counts are explicit per kind
 * (MCQ / MSQ / NAT) rather than one total, because the kind mix is the thing a
 * student is actually choosing.
 *
 * In demo mode the panel says plainly that questions come from the sample bank
 * — the student should never have to infer where a question came from. The
 * difficulty default is therefore `mixed`, not `medium`: the sample bank holds
 * only a few questions per subject, and a `medium` default would make the very
 * first request come back short with no obvious reason why.
 */
export function PracticeConfigForm({
  onStart,
  busy = false,
  documents,
  documentsError,
  onRetryDocuments,
  initialDocumentId,
}: {
  onStart: (config: PracticeConfig) => void;
  busy?: boolean;
  /** Ready documents, when Supabase is configured. Empty otherwise. */
  documents?: Array<{ id: string; filename: string }>;
  documentsError?: string | null;
  onRetryDocuments?: () => void;
  initialDocumentId?: string | null;
}) {
  const subjects = React.useMemo(() => sampleSubjects(), []);
  const [branch, setBranch] = React.useState("Computer Science");
  const [subject, setSubject] = React.useState(subjects[0] ?? "");
  const [topic, setTopic] = React.useState("");
  const [difficulty, setDifficulty] = React.useState<PracticeDifficulty>("mixed");
  const [counts, setCounts] = React.useState<Record<QuestionKind, number>>({
    MCQ: 4,
    MSQ: 0,
    NAT: 0,
  });
  const [sourceDocumentId, setSourceDocumentId] = React.useState<string | null>(
    initialDocumentId ?? null,
  );
  const [error, setError] = React.useState<string | null>(null);

  React.useEffect(() => {
    if (initialDocumentId) {
      setSourceDocumentId(initialDocumentId);
    }
  }, [initialDocumentId]);

  const topics = React.useMemo(() => sampleTopics(subject), [subject]);
  const total = counts.MCQ + counts.MSQ + counts.NAT;

  const setCount = (kind: QuestionKind, raw: string) => {
    const value = raw === "" ? 0 : Number(raw);
    setCounts((prev) => ({ ...prev, [kind]: Number.isFinite(value) ? value : 0 }));
  };

  const submit = (event: React.FormEvent) => {
    event.preventDefault();
    const verdict = validatePracticeConfig({
      branch,
      subject,
      topic: topic.trim() === "" ? null : topic,
      difficulty,
      counts,
      sourceDocumentId,
    });
    if (!verdict.ok) {
      setError(verdict.error);
      return;
    }
    setError(null);
    onStart(verdict.config);
  };

  return (
    <Card as="form" onSubmit={submit} variant="accent" aria-busy={busy || undefined}>
      <CardHeader
        icon={Sparkles}
        title="Set up a practice paper"
        description={
          DEMO_MODE
            ? "Questions come from the built-in sample bank and are labelled as sample questions — no model is called."
            : "Questions are generated by the model from the subject and difficulty you choose."
        }
      />

      <CardBody className="space-y-3.5">
        <div className="grid gap-3.5 sm:grid-cols-2">
          <Field label="Branch" id="practice-branch">
            <Input
              id="practice-branch"
              value={branch}
              onChange={(event) => setBranch(event.target.value)}
            />
          </Field>

          <Field label="Subject" id="practice-subject">
            <Input
              id="practice-subject"
              list="practice-subjects"
              value={subject}
              onChange={(event) => {
                setSubject(event.target.value);
                setTopic("");
              }}
            />
            <datalist id="practice-subjects">
              {subjects.map((value) => (
                <option key={value} value={value} />
              ))}
            </datalist>
          </Field>

          <Field label="Topic (optional)" id="practice-topic">
            <Input
              id="practice-topic"
              list="practice-topics"
              value={topic}
              placeholder="Any topic in the subject"
              onChange={(event) => setTopic(event.target.value)}
            />
            <datalist id="practice-topics">
              {topics.map((value) => (
                <option key={value} value={value} />
              ))}
            </datalist>
          </Field>

          <Field label="Difficulty" id="practice-difficulty">
            <select
              id="practice-difficulty"
              value={difficulty}
              onChange={(event) => setDifficulty(event.target.value as PracticeDifficulty)}
              className="h-10 w-full rounded-[var(--r-md)] border border-[var(--border)] bg-[var(--surface)] px-3 text-sm text-[var(--fg)] focus:border-[var(--accent)] focus:outline-none focus:ring-4 focus:ring-[var(--accent)]/12"
            >
              {PRACTICE_DIFFICULTIES.map((value) => (
                <option key={value} value={value}>
                  {value}
                </option>
              ))}
            </select>
          </Field>
        </div>

        <fieldset>
          <legend className="mb-1.5 text-[13px] font-medium text-[var(--fg)]">
            How many of each kind
          </legend>
          <div className="grid gap-3 sm:grid-cols-3">
            {(["MCQ", "MSQ", "NAT"] as const).map((kind) => (
              <Field
                key={kind}
                label={
                  kind === "MCQ"
                    ? "MCQ (single answer)"
                    : kind === "MSQ"
                      ? "MSQ (multiple answers)"
                      : "NAT (numeric)"
                }
                id={`practice-count-${kind}`}
              >
                <Input
                  id={`practice-count-${kind}`}
                  type="number"
                  min={0}
                  max={MAX_PRACTICE_QUESTIONS}
                  value={counts[kind]}
                  onChange={(event) => setCount(kind, event.target.value)}
                  className="tabular-nums"
                />
              </Field>
            ))}
          </div>
          <p className="mt-1.5 text-[12px] text-[var(--fg-subtle)]">
            {total} question{total === 1 ? "" : "s"} · at most {MAX_PRACTICE_QUESTIONS} per paper.
          </p>
        </fieldset>

        {documents && documents.length > 0 && (
          <Field
            label="Base the questions on one of your documents (optional)"
            id="practice-source"
            hint="Only ready documents are listed. The questions are still labelled AI-generated."
          >
            <select
              id="practice-source"
              value={sourceDocumentId ?? ""}
              onChange={(event) =>
                setSourceDocumentId(event.target.value === "" ? null : event.target.value)
              }
              className="h-10 w-full rounded-[var(--r-md)] border border-[var(--border)] bg-[var(--surface)] px-3 text-sm text-[var(--fg)] focus:border-[var(--accent)] focus:outline-none focus:ring-4 focus:ring-[var(--accent)]/12"
            >
              <option value="">No document — general practice</option>
              {documents.map((doc) => (
                <option key={doc.id} value={doc.id}>
                  {doc.filename}
                </option>
              ))}
            </select>
          </Field>
        )}

        {documentsError && (
          <Alert tone="danger" title="Documents unavailable" action={onRetryDocuments ? <Button variant="secondary" size="sm" onClick={onRetryDocuments}>Retry</Button> : undefined}>
            {documentsError}
          </Alert>
        )}

        {error && (
          <p role="alert" className="text-[12.5px] text-[var(--danger)]">
            {error}
          </p>
        )}

        <Button type="submit" disabled={busy} loading={busy}>
          Start practice
        </Button>
      </CardBody>
    </Card>
  );
}
