/** A primary navigation area and whether the app can actually serve it. */
export interface PrimaryArea {
  key: "dashboard" | "assistant" | "documents" | "practice" | "tests" | "analysis" | "settings";
  label: string;
  /** Route, or null when the area has no route yet. */
  href: string | null;
  /** `false` ⇒ do not render a link. See docs/AARAGATE-UI-AUDIT.md §8.1. */
  implemented: boolean;
  blurb: string;
}

